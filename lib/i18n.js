export function formatText(text, values = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '');
}

export function makeT(lang) {
  return (key, values) => formatText(I18N[lang]?.[key] ?? I18N.nl[key] ?? key, values);
}
